export function useT() {
  const { language } = useApp();
  return (s: string) => (language === 'kk' ? KK[s] ?? s : s);
}

export function formatAddress(p: Place, t: (s: string) => string) {
  return `${p.city}, ${t('ул.')} ${t(p.street)} ${p.house}`;
}
